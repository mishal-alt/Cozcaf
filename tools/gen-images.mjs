// Reads the real pixel size of every JPEG in public/img and writes src/data/images.ts.
// Run after adding or replacing photos:  node tools/gen-images.mjs
import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../public/img/', import.meta.url).pathname;
const groups = new Map();
for (const f of readdirSync(dir).sort()) {
  const m = f.match(/^(.+)-(\d+)\.jpg$/);
  if (!m) continue;
  const out = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', dir + f]).toString();
  const w = +out.match(/pixelWidth: (\d+)/)[1];
  const h = +out.match(/pixelHeight: (\d+)/)[1];
  if (!groups.has(m[1])) groups.set(m[1], []);
  groups.get(m[1]).push({ w: +m[2], h, file: f });
  if (w !== +m[2]) throw new Error(`${f}: name says ${m[2]} but file is ${w} wide`);
}
let ts = `// Generated by tools/gen-images.mjs. Do not edit by hand.\n`;
ts += `export interface ImageSet { /** widths available, ascending */ widths: readonly number[]; /** height of each width, same order */ heights: readonly number[]; }\n\n`;
ts += `export const images = {\n`;
for (const [name, list] of groups) {
  list.sort((a, b) => a.w - b.w);
  ts += `  ${JSON.stringify(name)}: { widths: [${list.map(x => x.w)}], heights: [${list.map(x => x.h)}] },\n`;
}
ts += `} as const satisfies Record<string, ImageSet>;\n\nexport type ImageName = keyof typeof images;\n`;
writeFileSync(new URL('../src/data/images.ts', import.meta.url), ts);
console.log(ts);
